const GRS80_A = 6378137;
const GRS80_F = 1 / 298.257222101;
const M0 = 0.9999;
const D2R = Math.PI / 180;
const P0 = 36 * D2R;
const L0 = (139 + 50 / 60) * D2R;
const N = GRS80_F / (2 - GRS80_F);
const N2 = N * N;
const N3 = N2 * N;
const N4 = N3 * N;
const N5 = N4 * N;
const A0 = 1 + N2 / 4 + N4 / 64;
const A1 = -1.5 * (N - N3 / 8 - N5 / 64);
const A2 = (15 / 16) * (N2 - N4 / 4);
const A3 = (-35 / 48) * (N3 - (5 / 16) * N5);
const A4 = (315 / 512) * N4;
const A5 = (-693 / 1280) * N5;
const AB = ((M0 * GRS80_A) / (1 + N)) * A0;
const SP0 =
  ((M0 * GRS80_A) / (1 + N)) *
  (A0 * P0 +
    A1 * Math.sin(2 * P0) +
    A2 * Math.sin(4 * P0) +
    A3 * Math.sin(6 * P0) +
    A4 * Math.sin(8 * P0) +
    A5 * Math.sin(10 * P0));
const AL = [
  0,
  0.5 * N - (2 / 3) * N2 + (5 / 16) * N3 + (41 / 180) * N4 - (127 / 288) * N5,
  (13 / 48) * N2 - (3 / 5) * N3 + (557 / 1440) * N4 + (281 / 630) * N5,
  (61 / 240) * N3 - (103 / 140) * N4 + (15061 / 26880) * N5,
  (49561 / 161280) * N4 - (179 / 168) * N5,
  (34729 / 80640) * N5,
];
const TSN = (2 * Math.sqrt(N)) / (1 + N);

function wgs84ToLocal(cam, lon, lat, elevM = 0) {
  const phi = lat * D2R;
  const dl = lon * D2R - L0;
  const sp = Math.sin(phi);
  const t = Math.sinh(Math.atanh(sp) - TSN * Math.atanh(TSN * sp));
  const tb = Math.hypot(1, t);
  const xp = Math.atan2(t, Math.cos(dl));
  const ep = Math.atanh(Math.sin(dl) / tb);
  let xi = xp;
  let et = ep;
  for (let j = 1; j <= 5; j++) {
    xi += AL[j] * Math.sin(2 * j * xp) * Math.cosh(2 * j * ep);
    et += AL[j] * Math.cos(2 * j * xp) * Math.sinh(2 * j * ep);
  }
  return [
    AB * et - cam.originEpsg6677.easting,
    AB * xi - SP0 - cam.originEpsg6677.northing,
    elevM,
  ];
}

function wgs84ToImage(cam, lon, lat, elevM = 0) {
  const loc = wgs84ToLocal(cam, lon, lat, elevM);
  const dx = loc[0] - cam.cameraOriginLocalM[0];
  const dy = loc[1] - cam.cameraOriginLocalM[1];
  const dz = loc[2] - cam.cameraOriginLocalM[2];
  const cx =
    dx * cam.basis.right[0] +
    dy * cam.basis.right[1] +
    dz * cam.basis.right[2];
  const cy =
    dx * cam.basis.up[0] +
    dy * cam.basis.up[1] +
    dz * cam.basis.up[2];
  return {
    px: cam.imageOriginPx.x + cx / cam.metersPerPixel,
    py: cam.imageOriginPx.y - cy / cam.metersPerPixel,
  };
}

