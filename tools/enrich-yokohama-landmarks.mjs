function main() {
  const rootDir = process.cwd();
  const releaseDir = path.join(rootDir, "viewer", "public", "releases", "full-yokohama-v1");
  const cam = JSON.parse(fs.readFileSync(path.join(releaseDir, "camera.json"), "utf8"));
  const lmPath = path.join(releaseDir, "landmarks.json");
  const payload = JSON.parse(fs.readFileSync(lmPath, "utf8"));

  // Validate projections & EN cleanliness for all additions
  for (const item of CURATED_ADDITIONS) {
    const img = wgs84ToImage(cam, item.lon, item.lat, item.elevationM);
    if (
      img.px < 30 ||
      img.px > cam.imageWidthPx - 30 ||
      img.py < 30 ||
      img.py > cam.imageHeightPx - 30
    ) {
      throw new Error(
        `${item.id} (${item.nameJa}) projected outside safe canvas bounds: px=${img.px.toFixed(1)} py=${img.py.toFixed(1)}`,
      );
    }
    if (HAS_JA(item.nameEn) || HAS_JA(item.descriptionEn)) {
      throw new Error(`Japanese characters found in EN fields for ${item.id}`);
    }
  }

  // Update lm-nissan-hq coordinates cleanly to exact OSM location
  const baseLandmarks = (payload.landmarks || [])
    .filter((l) => !String(l.id).startsWith("cur-"))
    .map((l) => {
      if (l.id === "lm-nissan-hq") {
        return { ...l, lon: 139.626257, lat: 35.463554, elevationM: 42 };
      }
      return l;
    });

  const basePois = (payload.pois || [])
    .filter((p) => !String(p.id).startsWith("cur-"))
    .map((p) => {
      if (p.id === "lm-nissan-hq") {
        return { ...p, lon: 139.626257, lat: 35.463554, elevationM: 42 };
      }
      return p;
    });

  const newPois = CURATED_ADDITIONS.map((item) => ({
    id: item.id,
    osmId: 0,
    featureId: 2,
    nameJa: item.nameJa,
    nameEn: item.nameEn,
    category: item.category,
    lon: item.lon,
    lat: item.lat,
    elevationM: item.elevationM,
    heightM: item.heightM,
    descriptionJa: item.descriptionJa,
    descriptionEn: item.descriptionEn,
    tier: item.tier,
    googleMapsUrl: `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${item.nameJa} 横浜`)}`,
  }));

  const newLandmarks = CURATED_ADDITIONS.filter((i) => i.inLandmarks).map((item) => ({
    id: item.id,
    featureId: 2,
    nameJa: item.nameJa,
    nameEn: item.nameEn,
    category: item.category === "station" ? "station" : "landmark",
    lon: item.lon,
    lat: item.lat,
    elevationM: item.elevationM,
    heightM: item.heightM,
    descriptionJa: item.descriptionJa,
    descriptionEn: item.descriptionEn,
    sourceKind: "osm-odbl",
    tier: item.tier,
    googleMapsUrl: `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${item.nameJa} 横浜`)}`,
  }));

  payload.landmarks = [...baseLandmarks, ...newLandmarks];
  // Put curated Tier 1/2 entries right before Shinko minor OSM POIs
  const baseCuratedLmIds = new Set(baseLandmarks.map((l) => l.id));
  const topBasePois = basePois.filter((p) => baseCuratedLmIds.has(p.id));
  const otherBasePois = basePois.filter((p) => !baseCuratedLmIds.has(p.id));
  payload.pois = [...topBasePois, ...newPois, ...otherBasePois];

  fs.writeFileSync(lmPath, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
  console.log(
    `Enriched landmarks.json cleanly: landmarks=${payload.landmarks.length} (+${newLandmarks.length}), pois=${payload.pois.length} (+${newPois.length})`,
  );
}

main();
